"""Tests for the documentation drift checkers and the diagram generator."""

import importlib.util
from pathlib import Path
from types import ModuleType

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]


def _load(name: str) -> ModuleType:
    """Import a script from scripts/ as a module (scripts import each other by bare name)."""
    import sys

    scripts = str(REPO_ROOT / "scripts")
    if scripts not in sys.path:
        sys.path.insert(0, scripts)
    spec = importlib.util.spec_from_file_location(name, REPO_ROOT / "scripts" / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def test_repository_passes_docs_sync_and_delivery_checks() -> None:
    """The checked-in tree has no drift."""
    assert _load("check_delivery_docs").check() == []
    assert _load("check_docs_sync").main() == 0


def test_version_files_detects_a_mismatching_version(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """VERSION, _version.py, pyproject and the CHANGELOG must agree."""
    sync = _load("check_docs_sync")
    (tmp_path / "src/arc_runner").mkdir(parents=True)
    (tmp_path / "VERSION").write_text("1.2.3\n", encoding="utf-8")
    (tmp_path / "src/arc_runner/_version.py").write_text('__version__: str = "1.2.4"\n', encoding="utf-8")
    (tmp_path / "pyproject.toml").write_text('version = "1.2.3"\n', encoding="utf-8")
    (tmp_path / "CHANGELOG.md").write_text("## [UNRELEASED]\n\n## [1.2.2]\n", encoding="utf-8")
    monkeypatch.setattr(sync, "REPO_ROOT", tmp_path)
    problems = sync.version_files()
    assert len(problems) == 2
    assert any("_version.py" in p for p in problems) and any("CHANGELOG" in p for p in problems)


def test_class_missing_from_diagram_is_reported(monkeypatch: pytest.MonkeyPatch) -> None:
    """A class that exists in the code but not in the generated class diagram is flagged as stale."""
    sync = _load("check_docs_sync")
    generator = _load("generate_diagrams")
    real = generator.parse_classes()
    monkeypatch.setattr(generator, "parse_classes", lambda: {**real, "BrandNewClassWithNoDiagram": {"module": "x", "bases": [], "methods": [], "fields": []}})
    problems = sync.diagram_coverage()
    assert any("BrandNewClassWithNoDiagram" in p for p in problems)


def test_stale_stamp_and_missing_files_are_reported(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A diagram stamped with an old version, and a missing partner file, are both reported."""
    sync = _load("check_docs_sync")
    (tmp_path / "uml").mkdir()
    (tmp_path / "drawio").mkdir()
    (tmp_path / "VERSION").write_text("2.0.0\n", encoding="utf-8")
    stamp = "<!-- Generated by scripts/generate_diagrams.py | VERSION 1.0.0 | git abc1234 | udm 0123456789ab -->"
    (tmp_path / "uml" / "package_diagram.md").write_text(stamp, encoding="utf-8")
    monkeypatch.setattr(sync, "REPO_ROOT", tmp_path)
    problems = sync.diagram_files_and_stamps()
    assert any("stamped 1.0.0 but VERSION is 2.0.0" in p for p in problems)
    assert any("missing drawio/package_diagram.drawio" in p for p in problems)
    assert any("missing uml/component_diagram.md" in p for p in problems)


def test_generator_rejects_call_graph_edges_to_unknown_functions() -> None:
    """The call graph cannot name a function that does not exist."""
    generator = _load("generate_diagrams")
    with pytest.raises(SystemExit):
        generator.verify_call_graph([{"from": "NoSuchClass.method", "to": "arc_not_a_c_function", "lang": "py"}])
    generator.verify_call_graph([{"from": "FlashStreamWeightManager.acquire_layer_weights", "to": "arc_range_ok", "lang": "c"}])


def test_generator_is_idempotent_and_keeps_old_content(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Writing a block twice leaves one block, and the earlier content of the file is preserved."""
    generator = _load("generate_diagrams")
    (tmp_path / "uml").mkdir()
    target = tmp_path / "uml" / "state_diagram.md"
    target.write_text("# State\r\n\r\nold content\r\n", encoding="utf-8", newline="")
    monkeypatch.setattr(generator, "REPO_ROOT", tmp_path)
    stamp = generator.stamp_text("1.0.0", "abc1234", "0123456789ab")
    generator.write_markdown("state", "heading", "stateDiagram-v2\n    [*] --> A", stamp)
    generator.write_markdown("state", "heading", "stateDiagram-v2\n    [*] --> A", stamp)
    text = target.read_bytes().decode("utf-8")
    assert text.count("<!-- native-layer:begin -->") == 1
    assert "old content" in text and "\r\n" in text and "\n\n" not in text.replace("\r\n", "")


def test_delivery_checker_reports_front_matter_index_and_log_problems(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Malformed documents, duplicate ids, stale index rows and gaps in the decision log are reported."""
    delivery = _load("check_delivery_docs")
    root = tmp_path / "docs" / "delivery"
    root.mkdir(parents=True)
    monkeypatch.setattr(delivery, "REPO_ROOT", tmp_path)
    monkeypatch.setattr(delivery, "DELIVERY", root)

    def doc(name: str, doc_id: str, version: str = "1.0.0", revision: bool = True) -> None:
        history = f"\n| {version} | 2026-10-29 | x | y | z | c |\n" if revision else "\n"
        (root / name).write_text(
            f"---\ndoc_id: {doc_id}\ntitle: t\nstage: s\nversion: {version}\nstatus: draft\ncreated: 2026-10-29\nupdated: 2026-10-29\n---\n{history}",
            encoding="utf-8",
        )

    doc("a.md", "DOC-A")
    doc("b.md", "DOC-A")
    doc("c.md", "DOC-C", revision=False)
    doc("d.md", "DOC-D", version="1.0")
    (root / "e.md").write_text("no front matter\n", encoding="utf-8")
    (root / "INDEX.md").write_text("| DOC-A | t | 0.9.0 | draft | s | a.md |\n| DOC-GHOST | t | 1.0.0 | draft | s | g.md |\n", encoding="utf-8")
    (root / "DECISION_LOG.md").write_text("| DL-001 | x |\n| DL-003 | y |\n", encoding="utf-8")
    problems = " | ".join(delivery.check())
    assert "already used by" in problems
    assert "no revision-history row" in problems
    assert "is not x.y.z" in problems
    assert "front matter missing" in problems
    assert "INDEX.md row for DOC-A is stale" in problems
    assert "lists unknown DOC-GHOST" in problems
    assert "gaps" in problems


def test_state_diagram_labels_never_contain_a_second_colon_or_semicolon() -> None:
    """Mermaid reads the first colon of a transition as the label separator; later colons break parsing."""
    import importlib.util
    from pathlib import Path

    root = Path(__file__).resolve().parents[1]
    spec = importlib.util.spec_from_file_location("generate_diagrams", root / "scripts" / "generate_diagrams.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    section = {"nodes": [{"id": "A", "label": "A"}, {"id": "B", "label": "B"}], "edges": [{"from": "A", "to": "B", "label": "reserve: one; two"}]}
    transition = [line for line in module.state_diagram(section).splitlines() if "-->" in line][0]
    assert transition.count(":") == 1 and ";" not in transition


