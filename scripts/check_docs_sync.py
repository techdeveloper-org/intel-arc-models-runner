"""Check that code, documentation and diagrams have not drifted apart (stdlib only).

Checks: (a) every uml/<x>_diagram.md has drawio/<x>_diagram.drawio and all 13 types exist; (b) the generated
stamp in every diagram has the current VERSION and a commit that is an ancestor of HEAD; (c) every class of the
diagram scope appears in the class diagram and every subpackage in the package diagram; (d) benchmark documents
that are not generated carry a provenance note and the generated table is current; (e) relative links in the
README and docs resolve; (f) VERSION, src/arc_runner/_version.py, pyproject.toml and the top released CHANGELOG
entry agree; (g) the delivery documents pass check_delivery_docs.py.

Usage: python scripts/check_docs_sync.py      (exit 1 and a list of stale items on any mismatch)
"""

from pathlib import Path
import re
import subprocess
import sys
from typing import List

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

DIAGRAMS = [
    "package", "component", "class", "sequence", "state", "activity", "deployment", "usecase",
    "object", "composite", "interaction", "communication", "call_graph",
]
STAMP = re.compile(r"Generated by scripts/generate_diagrams\.py \| VERSION (\S+) \| git (\S+) \| udm (\S+)")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")


def version_files() -> List[str]:
    """Compare every place that states the version.

    Returns:
        List[str]: Problems found.
    """
    version = (REPO_ROOT / "VERSION").read_text(encoding="utf-8").strip()
    problems: List[str] = []
    init = re.search(r'__version__: str = "([^"]+)"', (REPO_ROOT / "src/arc_runner/_version.py").read_text(encoding="utf-8"))
    pyproject = re.search(r'^version = "([^"]+)"', (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"), re.M)
    changelog = re.search(r"^## \[(\d+\.\d+\.\d+)\]", (REPO_ROOT / "CHANGELOG.md").read_text(encoding="utf-8"), re.M)
    for name, found in (("_version.py", init), ("pyproject.toml", pyproject), ("CHANGELOG.md top release", changelog)):
        if not found or found.group(1) != version:
            problems.append(f"{name} version {found.group(1) if found else 'missing'} != VERSION {version}")
    return problems


def is_ancestor(sha: str) -> bool:
    """Return True if sha is an ancestor of HEAD.

    Args:
        sha: Short or full commit id.
    """
    if sha == "unknown":
        return False
    return subprocess.run(["git", "-C", str(REPO_ROOT), "merge-base", "--is-ancestor", sha, "HEAD"], capture_output=True).returncode == 0


def diagram_files_and_stamps() -> List[str]:
    """Check the 13+13 diagram files and their stamps.

    Returns:
        List[str]: Problems found.
    """
    problems: List[str] = []
    version = (REPO_ROOT / "VERSION").read_text(encoding="utf-8").strip()
    for kind in DIAGRAMS:
        uml = REPO_ROOT / "uml" / f"{kind}_diagram.md"
        drawio = REPO_ROOT / "drawio" / f"{kind}_diagram.drawio"
        for path in (uml, drawio):
            if not path.exists():
                problems.append(f"missing {path.relative_to(REPO_ROOT)}")
                continue
            match = STAMP.search(path.read_text(encoding="utf-8"))
            if not match:
                problems.append(f"{path.relative_to(REPO_ROOT)} has no generated stamp; run python scripts/generate_diagrams.py")
            elif match.group(1) != version:
                problems.append(f"{path.relative_to(REPO_ROOT)} stamped {match.group(1)} but VERSION is {version}; regenerate diagrams")
            elif not is_ancestor(match.group(2)):
                problems.append(f"{path.relative_to(REPO_ROOT)} stamped with commit {match.group(2)} that is not an ancestor of HEAD")
    return problems


def diagram_coverage() -> List[str]:
    """Check that classes and packages of the code appear in the generated diagrams.

    Returns:
        List[str]: Problems found.
    """
    import generate_diagrams as gen

    problems: List[str] = []
    class_text = (REPO_ROOT / "uml" / "class_diagram.md").read_text(encoding="utf-8")
    for name in gen.parse_classes():
        if f"class {name} " not in class_text:
            problems.append(f"class {name} is missing from uml/class_diagram.md; run python scripts/generate_diagrams.py")
    package_text = (REPO_ROOT / "uml" / "package_diagram.md").read_text(encoding="utf-8")
    packages, _edges = gen.parse_packages()
    for package in packages:
        if f'{package}["{package}"]' not in package_text:
            problems.append(f"package {package} is missing from uml/package_diagram.md; run python scripts/generate_diagrams.py")
    return problems


def benchmark_docs() -> List[str]:
    """Check provenance notes and the generated benchmark table.

    Returns:
        List[str]: Problems found.
    """
    problems: List[str] = []
    for path in sorted((REPO_ROOT / "docs" / "benchmarks").glob("*.md")):
        if path.name in ("README.md", "METHOD.md"):
            continue
        if "Provenance status" not in path.read_text(encoding="utf-8"):
            problems.append(f"{path.relative_to(REPO_ROOT)} has no provenance note")
    import render_bench_docs

    if render_bench_docs.main(["--check"]) != 0:
        problems.append("docs/benchmarks/README.md generated table is stale; run python scripts/render_bench_docs.py")
    return problems


def links() -> List[str]:
    """Check relative links in the README and docs.

    Returns:
        List[str]: Problems found.
    """
    problems: List[str] = []
    files = [REPO_ROOT / "README.md", *sorted((REPO_ROOT / "docs").rglob("*.md"))]
    for path in files:
        in_fence = False
        for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
            if in_fence:
                continue
            for target in LINK.findall(line):
                if re.match(r"^(https?:|mailto:|file:|#)", target):
                    continue
                relative = target.split("#")[0]
                if relative and not (path.parent / relative).exists():
                    problems.append(f"{path.relative_to(REPO_ROOT)}:{number} broken link {target}")
    return problems


def delivery_docs() -> List[str]:
    """Run the delivery document checker.

    Returns:
        List[str]: Problems found.
    """
    import check_delivery_docs

    return check_delivery_docs.check()


def main() -> int:
    """Run all checks and print every problem.

    Returns:
        int: 0 if everything is in sync, 1 otherwise.
    """
    problems = version_files() + diagram_files_and_stamps() + diagram_coverage() + benchmark_docs() + links() + delivery_docs()
    for problem in problems:
        print(problem)
    print(f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
