"""Generate the v0.2.0 native-layer sections of the 13 UML (Mermaid) and 13 Draw.io diagrams.

Input: docs/delivery/udm/native_layer.json (hand-built model) plus the class and import structure read
from the source with `ast`, so class and package diagrams cannot drift from the code. Call-graph edges
are verified against the Python AST and the C sources; a missing function is an error.

Output: a marked block appended to (or replaced in) each uml/<type>.md and an extra Draw.io page named
"Native layer (v0.2.0)" in each drawio/<type>.drawio. Every output carries a stamp with the VERSION,
the git commit and the model hash; scripts/check_docs_sync.py verifies the stamps. Earlier diagram
content is left untouched (it is not regenerated by this script).

Usage: python scripts/generate_diagrams.py
"""

import ast
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
from typing import Any, Dict, List, Set, Tuple
from xml.sax.saxutils import escape

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC = REPO_ROOT / "src" / "arc_runner"
UDM_PATH = REPO_ROOT / "docs" / "delivery" / "udm" / "native_layer.json"
BEGIN = "<!-- native-layer:begin -->"
END = "<!-- native-layer:end -->"
PAGE_NAME = "Native layer (v0.2.0)"
DIAGRAMS = [
    "package", "component", "class", "sequence", "state", "activity", "deployment", "usecase",
    "object", "composite", "interaction", "communication", "call_graph",
]
CLASS_SCOPE = [
    "native/bridge.py", "engine/flash_stream/weight_streamer.py", "devices/sysman.py", "engine/models.py",
    "engine/kv_cache.py", "benchmark/stats.py", "benchmark/results.py",
]


def git_short_sha() -> str:
    """Return the current commit's short SHA, or 'unknown'."""
    result = subprocess.run(["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else "unknown"


def stamp_text(version: str, sha: str, udm_hash: str) -> str:
    """Build the stamp comment text.

    Args:
        version: Contents of the VERSION file.
        sha: Short git SHA.
        udm_hash: First 12 hex characters of the model hash.
    """
    return f"Generated by scripts/generate_diagrams.py | VERSION {version} | git {sha} | udm {udm_hash}"


def parse_classes() -> Dict[str, Dict[str, Any]]:
    """Read classes, bases and method names from the diagram scope with ast.

    Returns:
        Dict[str, Dict[str, Any]]: class name -> {module, bases, methods, fields}.
    """
    classes: Dict[str, Dict[str, Any]] = {}
    for relative in CLASS_SCOPE:
        tree = ast.parse((SRC / relative).read_text(encoding="utf-8"))
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            methods = [n.name for n in node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not (n.name.startswith("__") and n.name != "__init__")]
            fields = [n.target.id for n in node.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)]
            bases = [b.id for b in node.bases if isinstance(b, ast.Name)]
            classes[node.name] = {"module": relative, "bases": bases, "methods": methods, "fields": fields}
    return classes


def parse_packages() -> Tuple[List[str], Set[Tuple[str, str]]]:
    """Read subpackages and import edges between them with ast.

    Returns:
        Tuple[List[str], Set[Tuple[str, str]]]: sorted package names and (importer, imported) pairs.
    """
    packages = sorted(p.name for p in SRC.iterdir() if p.is_dir() and (p / "__init__.py").exists())
    edges: Set[Tuple[str, str]] = set()
    for path in SRC.rglob("*.py"):
        parts = path.relative_to(SRC).parts
        importer = parts[0] if len(parts) > 1 else "(root)"
        if importer not in packages:
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            module = node.module if isinstance(node, ast.ImportFrom) and node.module else None
            if module and module.startswith("arc_runner."):
                target = module.split(".")[1]
                if target in packages and target != importer:
                    edges.add((importer, target))
    return packages, edges


def verify_call_graph(edges: List[Dict[str, str]]) -> None:
    """Fail if a call-graph edge names a function that does not exist.

    Args:
        edges: Call graph edges with a lang of py or c.

    Raises:
        SystemExit: If any endpoint cannot be found in the Python AST or the C sources.
    """
    py_names: Set[str] = set()
    for path in SRC.rglob("*.py"):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ClassDef):
                for member in node.body:
                    if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        py_names.add(f"{node.name}.{member.name}")
    c_text = "".join(p.read_text(encoding="utf-8") for p in (SRC / "native").glob("*.c"))
    missing = []
    for edge in edges:
        for end in (edge["from"], edge["to"]):
            is_c = "." not in end
            if is_c and not re.search(rf"\b{re.escape(end)}\s*\(", c_text):
                missing.append(end)
            if not is_c and end not in py_names:
                missing.append(end)
    if missing:
        raise SystemExit(f"call graph references unknown functions: {sorted(set(missing))}")


def q(text: str) -> str:
    """Make a label safe inside a double-quoted Mermaid string.

    Args:
        text: Raw label.
    """
    return text.replace('"', "'")


def flowchart(section: Dict[str, Any], direction: str = "LR") -> str:
    """Render nodes and edges as a Mermaid flowchart.

    Args:
        section: UDM section with nodes, edges and optional actors.
        direction: LR or TD.
    """
    lines = [f"flowchart {direction}"]
    for actor in section.get("actors", []):
        lines.append(f'    {actor}(["{actor}"])')
    for node in section["nodes"]:
        lines.append(f'    {node["id"]}["{q(node["label"])}"]')
    for edge in section["edges"]:
        label = f'|"{q(edge["label"])}"|' if edge.get("label") else ""
        lines.append(f'    {edge["from"]} -->{label} {edge["to"]}')
    return "\n".join(lines)


def state_diagram(section: Dict[str, Any]) -> str:
    """Render a UDM state section as a Mermaid stateDiagram-v2.

    Args:
        section: UDM section with nodes and edges ([*] marks initial and final).
    """
    lines = ["stateDiagram-v2"]
    lines += [f'    state "{q(n["label"])}" as {n["id"]}' for n in section["nodes"]]
    lines += [f'    {e["from"]} --> {e["to"]} : {q(e["label"])}' for e in section["edges"]]
    return "\n".join(lines)


def sequence_diagram(section: Dict[str, Any]) -> str:
    """Render a UDM sequence section as a Mermaid sequenceDiagram.

    Args:
        section: UDM section with participants and messages.
    """
    lines = ["sequenceDiagram"]
    lines += [f"    participant {p}" for p in section["participants"]]
    lines += [f'    {m["from"]}->>{m["to"]}: {q(m["text"])}' for m in section["messages"]]
    return "\n".join(lines)


def class_diagram(classes: Dict[str, Dict[str, Any]]) -> str:
    """Render the AST-derived classes as a Mermaid classDiagram.

    Args:
        classes: Result of parse_classes.
    """
    lines = ["classDiagram"]
    for name, info in sorted(classes.items()):
        lines.append(f"    class {name} {{")
        lines += [f"        +{f}" for f in info["fields"][:12]]
        lines += [f"        +{m}()" for m in info["methods"][:16]]
        lines.append("    }")
    for name, info in sorted(classes.items()):
        lines += [f"    {base} <|-- {name}" for base in info["bases"] if base in classes]
    return "\n".join(lines)


def package_diagram(packages: List[str], edges: Set[Tuple[str, str]]) -> str:
    """Render subpackages and imports as a Mermaid flowchart.

    Args:
        packages: Subpackage names.
        edges: (importer, imported) pairs.
    """
    lines = ["flowchart LR"]
    lines += [f'    {p}["{p}"]' for p in packages]
    lines += [f"    {a} --> {b}" for a, b in sorted(edges)]
    return "\n".join(lines)


def call_graph(edges: List[Dict[str, str]]) -> str:
    """Render the verified call graph as a Mermaid flowchart with C functions marked.

    Args:
        edges: Call graph edges.
    """
    def node_id(name: str) -> str:
        return re.sub(r"\W", "_", name)

    lines = ["flowchart LR"]
    seen: Set[str] = set()
    for edge in edges:
        for end in (edge["from"], edge["to"]):
            if end not in seen:
                seen.add(end)
                suffix = ":::c" if "." not in end else ""
                lines.append(f'    {node_id(end)}["{end}"]{suffix}')
    lines += [f'    {node_id(e["from"])} --> {node_id(e["to"])}' for e in edges]
    lines.append("    classDef c fill:#fde,stroke:#a33")
    return "\n".join(lines)


def build_mermaid(udm: Dict[str, Any]) -> Dict[str, Tuple[str, str]]:
    """Build the Mermaid source of every diagram type.

    Args:
        udm: Parsed model.

    Returns:
        Dict[str, Tuple[str, str]]: type -> (heading, mermaid source).
    """
    packages, imports = parse_packages()
    classes = parse_classes()
    verify_call_graph(udm["call_graph"]["edges"])
    return {
        "package": ("Package structure (from the source tree)", package_diagram(packages, imports)),
        "component": (udm["component"]["title"], flowchart(udm["component"])),
        "class": ("Classes of the native layer, ring buffer, Sysman, telemetry and benchmark gates (from the source)", class_diagram(classes)),
        "sequence": (udm["sequence"]["title"], sequence_diagram(udm["sequence"])),
        "state": (udm["state"]["title"], state_diagram(udm["state"])),
        "activity": (udm["activity"]["title"], flowchart(udm["activity"], "TD")),
        "deployment": (udm["deployment"]["title"], flowchart(udm["deployment"])),
        "usecase": (udm["usecase"]["title"], flowchart(udm["usecase"])),
        "object": (udm["object"]["title"], flowchart(udm["object"])),
        "composite": (udm["composite"]["title"], flowchart(udm["composite"])),
        "interaction": (udm["interaction"]["title"], flowchart(udm["interaction"], "TD")),
        "communication": (udm["communication"]["title"], flowchart(udm["communication"])),
        "call_graph": (udm["call_graph"]["title"], call_graph(udm["call_graph"]["edges"])),
    }


def graph_for_drawio(kind: str, udm: Dict[str, Any]) -> Tuple[List[Tuple[str, str]], List[Tuple[str, str, str]]]:
    """Return (nodes, edges) for a diagram type in a Draw.io-friendly form.

    Args:
        kind: Diagram type.
        udm: Parsed model.

    Returns:
        Tuple: nodes as (id, label) and edges as (from, to, label).
    """
    if kind == "package":
        packages, imports = parse_packages()
        return [(p, p) for p in packages], [(a, b, "imports") for a, b in sorted(imports)]
    if kind == "class":
        classes = parse_classes()
        nodes = [(n, n + "\n" + "\n".join(i["fields"][:6] + [m + "()" for m in i["methods"][:10]])) for n, i in sorted(classes.items())]
        edges = [(b, n, "inherits") for n, i in classes.items() for b in i["bases"] if b in classes]
        return nodes, edges
    if kind == "sequence":
        sec = udm["sequence"]
        return [(p, p) for p in sec["participants"]], [(m["from"], m["to"], m["text"]) for m in sec["messages"]]
    if kind == "call_graph":
        names = []
        for e in udm["call_graph"]["edges"]:
            for end in (e["from"], e["to"]):
                if end not in names:
                    names.append(end)
        return [(re.sub(r"\W", "_", n), n) for n in names], [(re.sub(r"\W", "_", e["from"]), re.sub(r"\W", "_", e["to"]), "") for e in udm["call_graph"]["edges"]]
    sec = udm[kind]
    nodes = [(n["id"], n["label"]) for n in sec["nodes"]] + [(a, a) for a in sec.get("actors", [])]
    if kind == "state":
        nodes.append(("[*]", "start / end"))
    return nodes, [(e["from"], e["to"], e.get("label", "")) for e in sec["edges"]]


def drawio_page(nodes: List[Tuple[str, str]], edges: List[Tuple[str, str, str]]) -> str:
    """Lay nodes out in columns by dependency depth and render a Draw.io diagram page.

    Args:
        nodes: (id, label) pairs.
        edges: (from, to, label) triples.

    Returns:
        str: The <diagram> XML element.
    """
    ids = [n[0] for n in nodes]
    depth = {i: 0 for i in ids}
    for _ in range(len(ids)):
        for a, b, _label in edges:
            if a in depth and b in depth and a != b and depth[b] <= depth[a] and depth[a] < len(ids):
                depth[b] = depth[a] + 1
    columns: Dict[int, List[str]] = {}
    for i in ids:
        columns.setdefault(depth[i], []).append(i)
    position = {i: (40 + 300 * col, 40 + 120 * row) for col, members in columns.items() for row, i in enumerate(members)}
    cells = ['<mxCell id="0" />', '<mxCell id="1" parent="0" />']
    labels = dict(nodes)
    for index, node_id in enumerate(ids):
        x, y = position[node_id]
        lines = max(2, labels[node_id].count("\n") + 1 + len(labels[node_id]) // 34)
        height = min(60 + 16 * lines, 260)
        cells.append(
            f'<mxCell id="n{index}" value="{escape(labels[node_id], {chr(10): "&#10;", chr(34): "&quot;"})}" '
            f'style="rounded=1;whiteSpace=wrap;html=0;align=left;verticalAlign=top;" vertex="1" parent="1">'
            f'<mxGeometry x="{x}" y="{y}" width="240" height="{height}" as="geometry" /></mxCell>'
        )
    index_of = {n: i for i, n in enumerate(ids)}
    for k, (a, b, label) in enumerate(edges):
        if a in index_of and b in index_of:
            cells.append(
                f'<mxCell id="e{k}" value="{escape(label, {chr(34): "&quot;"})}" style="edgeStyle=orthogonalEdgeStyle;endArrow=block;html=1;" '
                f'edge="1" parent="1" source="n{index_of[a]}" target="n{index_of[b]}"><mxGeometry relative="1" as="geometry" /></mxCell>'
            )
    body = "\n        ".join(cells)
    return (
        f'<diagram id="native-layer" name="{PAGE_NAME}">\n    <mxGraphModel dx="1422" dy="762" grid="1" gridSize="10" guides="1" tooltips="1" connect="1" '
        f'arrows="1" fold="1" page="1" pageScale="1" pageWidth="1654" pageHeight="1169" math="0" shadow="0">\n      <root>\n        {body}\n      </root>\n    </mxGraphModel>\n  </diagram>'
    )


def write_markdown(kind: str, heading: str, mermaid: str, stamp: str) -> None:
    """Append or replace the marked native-layer block in a UML markdown file.

    Args:
        kind: Diagram type.
        heading: Section heading.
        mermaid: Mermaid source.
        stamp: Stamp text.
    """
    path = REPO_ROOT / "uml" / f"{kind}_diagram.md"
    raw = path.read_bytes().decode("utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    block = f"{BEGIN}\n<!-- {stamp} -->\n## v0.2.0 native layer: {heading}\n\n```mermaid\n{mermaid}\n```\n{END}\n"
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    text = pattern.sub("", text).rstrip("\n") + "\n\n" + block
    path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def write_drawio(kind: str, udm: Dict[str, Any], stamp: str) -> None:
    """Add or replace the native-layer page and the stamp comment in a Draw.io file.

    Args:
        kind: Diagram type.
        udm: Parsed model.
        stamp: Stamp text.
    """
    path = REPO_ROOT / "drawio" / f"{kind}_diagram.drawio"
    raw = path.read_bytes().decode("utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    text = re.sub(r"<!-- Generated by scripts/generate_diagrams\.py[^>]*-->\n?", "", text)
    text = re.sub(r"\s*<diagram id=\"native-layer\".*?</diagram>", "", text, flags=re.S)
    nodes, edges = graph_for_drawio(kind, udm)
    text = text.replace("</mxfile>", f"  {drawio_page(nodes, edges)}\n</mxfile>")
    text = text.replace("?>\n", f"?>\n<!-- {stamp} -->\n", 1)
    path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def main() -> int:
    """Generate every diagram and print a summary.

    Returns:
        int: 0 on success.
    """
    udm_bytes = UDM_PATH.read_bytes()
    udm = json.loads(udm_bytes)
    stamp = stamp_text((REPO_ROOT / "VERSION").read_text(encoding="utf-8").strip(), git_short_sha(), hashlib.sha256(udm_bytes).hexdigest()[:12])
    mermaid = build_mermaid(udm)
    for kind in DIAGRAMS:
        heading, source = mermaid[kind]
        write_markdown(kind, heading, source, stamp)
        write_drawio(kind, udm, stamp)
    print(f"generated {len(DIAGRAMS)} uml sections and {len(DIAGRAMS)} drawio pages: {stamp}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
